import SwiftUI
import UIKit
import ImageIO
import UniformTypeIdentifiers
import HippoPresentation

/// The system camera (`UIImagePickerController`, photo and video, photo mode first). Hands back the
/// still as a `CGImage` with its orientation and metadata, or the recorded movie's temporary URL.
struct CameraPicker: UIViewControllerRepresentable {
    let onResult: (CameraResult) -> Void
    let onCancel: () -> Void

    func makeUIViewController(context: Context) -> UIImagePickerController {
        let picker = UIImagePickerController()
        picker.sourceType = .camera
        picker.mediaTypes = [UTType.image.identifier, UTType.movie.identifier]
        picker.videoQuality = .typeHigh
        picker.cameraCaptureMode = .photo
        picker.delegate = context.coordinator
        return picker
    }

    func updateUIViewController(_ picker: UIImagePickerController, context: Context) {
        context.coordinator.parent = self
    }

    func makeCoordinator() -> Coordinator { Coordinator(parent: self) }

    final class Coordinator: NSObject, UIImagePickerControllerDelegate, UINavigationControllerDelegate {
        var parent: CameraPicker

        init(parent: CameraPicker) { self.parent = parent }

        func imagePickerController(_ picker: UIImagePickerController,
                                   didFinishPickingMediaWithInfo info: [UIImagePickerController.InfoKey: Any]) {
            if let url = info[.mediaURL] as? URL {
                parent.onResult(.video(url))
            } else if let image = info[.originalImage] as? UIImage, let cgImage = image.cgImage {
                let metadata = info[.mediaMetadata] as? [String: Any] ?? [:]
                parent.onResult(.photo(cgImage, orientation: Int32(CGImagePropertyOrientation(image.imageOrientation).rawValue),
                                       metadata: PhotoMetadata(metadata)))
            } else {
                parent.onCancel()
            }
        }

        func imagePickerControllerDidCancel(_ picker: UIImagePickerController) {
            parent.onCancel()
        }
    }
}

private extension CGImagePropertyOrientation {
    init(_ orientation: UIImage.Orientation) {
        switch orientation {
        case .up: self = .up
        case .upMirrored: self = .upMirrored
        case .down: self = .down
        case .downMirrored: self = .downMirrored
        case .left: self = .left
        case .leftMirrored: self = .leftMirrored
        case .right: self = .right
        case .rightMirrored: self = .rightMirrored
        @unknown default: self = .up
        }
    }
}
